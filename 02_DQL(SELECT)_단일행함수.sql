SELECT
		PATIENT_NAME
	 ,  SUBSTR(PATIENT_NAME, 1, 1) AS "성"
	 , 	SUBSTR(PATIENT_NAME, 2) AS "이름"
FROM
		PATIENT;

SELECT 
		PATIENT_NAME
	 ,  LPAD(PATIENT_NAME, 10, '*')
	 ,	RPAD(PATIENT_NAME, 10, '*')
FROM 
		PATIENT;


-- PAD는 진짜 많이 쓴다
-- 개인정보보호(마스킹 할 때 많이 씀)	
SELECT 
		PATIENT_NAME
	 ,  RPAD(SUBSTR(PATIENT_NAME, 1, 1), 4, '*')
	 , 	SUBSTR(PATIENT_NAME, 1, 1) || '*' || SUBSTR(PATIENT_NAME , 3)
FROM	
		PATIENT;

SELECT  '                DATA                     '
	 , TRIM('                  DATA                     ')
	 , LTRIM('AAAAAADATA', 'A')
	 , RTRIM('DATABBBBBB', 'B')
FROM
	   DUAL;

SELECT 
	    MOD(10, 3) -- 나머지연산
	 ,  ROUND(1.28546, 2) -- 소숫점 자리를 두번쨰 인자로 조절.
	 , 	CEIL(1.2)
	 ,	FLOOR(2.9)
	 ,	TRUNC(10.23235, 2) -- 버림
FROM
		DUAL;

SELECT 
		PATIENT_NAME
	 ,  HEIGHT_CM - 100 "표준체중"
	 ,  WEIGHT_KG
	 ,  ABS(WEIGHT_KG - (HEIGHT_CM -100)) "차이"
FROM
		PATIENT;


SELECT 
		SYSDATE 
FROM
		DUAL;

--환자 나이 조회
SELECT 
		PATIENT_NAME
	 , 	FLOOR(MONTHS_BETWEEN(SYSDATE, BIRTH_DATE) / 12)
	 , 	FLOOR(SYSDATE - ADMISSION_DATE)
FROM
		PATIENT;

