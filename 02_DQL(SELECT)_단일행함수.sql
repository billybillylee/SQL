--NULL 처리 함수 [매우 중요]
SELECT
		PATIENT_NAME
	 ,  DISCHARGE_DATE
	 , 	NVL(TO_CHAR(DISCHARGE_DATE, 'YYYY-MM-DD'), '입원중')
FROM
		PATIENT;

SELECT 
		PATIENT_NAME
	 , NVL(DOCTOR_ID, '미배정')
	 , NVL2(DOCTOR_ID, '배정완료', '미배정' )
FROM 
		PATIENT;

SELECT 
		PATIENT_NAME
	 , 	DECODE(GENDER, 'M', '남', 'F', '여') GENDER
	 , 	CASE GENDER 
	 		WHEN 'M' THEN '남성'
	 		WHEN 'F' THEN '여성'
	 		ELSE '성별선택안함'
	 	END 성별
FROM
		PATIENT;
		

		
