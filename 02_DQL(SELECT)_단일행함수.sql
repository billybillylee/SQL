SELECT 
		PATIENT_NAME
	 ,  ADMISSION_DATE
	 , 	TO_CHAR(ADMISSION_DATE, 'YYYY')
	 , 	TO_CHAR(ADMISSION_DATE, 'MM')
	 , 	TO_CHAR(ADMISSION_DATE, 'YYYY') - 2000
FROM 
		PATIENT;

SELECT 
		PATIENT_NAME
	 ,  ADMISSION_DATE
FROM 
		PATIENT
WHERE
		ADMISSION_DATE >= TO_DATE('2026-10-20', 'YYYY-MM-DD');

SELECT 
